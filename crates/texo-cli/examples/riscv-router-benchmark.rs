//! Reproducible fixed-placement router benchmark for Rica's `HardwareTestTop`.

use std::collections::BTreeMap;
use std::env;
use std::error::Error;
use std::fs::File;
use std::io::{BufRead, BufReader, BufWriter, Write};
use std::path::Path;
use std::time::Instant;

use serde_json::Value;
use sha2::{Digest, Sha256};
use struo_synth::synthesize;
use struo_target_ecp5::{
    JtaggBinding, MappingOptions, PllBinding, RegisterEnableFanoutConstraint,
    map_to_ecp5_with_options,
};
use texo_cli::{ecp5_checkpoint_ref, load_veryl_project};
use texo_flow::{
    Ecp5FlowOptions, Ecp5FlowStage, Evidence, Gate, PostMapSimulationPolicy, RoutingProgress,
    implement_struo_ecp5_with_progress,
};
use texo_struo::import_ecp5;
use texo_target_ecp5::{parse_lpf, read_architecture_cache};

const USAGE: &str = "\
Usage: riscv-router-benchmark PROJECT ARCH.txdb LPF PLL.json PLACEMENT CHECKPOINT.json
";

#[allow(clippy::too_many_lines)]
fn main() -> Result<(), Box<dyn Error>> {
    let mut args = env::args().skip(1);
    let project = args.next().ok_or(USAGE)?;
    let architecture_path = args.next().ok_or(USAGE)?;
    let lpf_path = args.next().ok_or(USAGE)?;
    let pll_path = args.next().ok_or(USAGE)?;
    let placement_path = args.next().ok_or(USAGE)?;
    let checkpoint_path = args.next().ok_or(USAGE)?;
    if args.next().is_some() {
        return Err(USAGE.into());
    }

    let loaded = load_veryl_project(Path::new(&project), Some("HardwareTestTop"))?;
    let synthesized = synthesize(&loaded.design)?;
    let mut mapped = map_to_ecp5_with_options(
        &synthesized.netlist,
        MappingOptions {
            timing_goal_mhz: 125,
            ..MappingOptions::default()
        },
    )?;
    mapped.bind_jtagg(&JtaggBinding::with_prefix("jtag"))?;
    let pll: PllBinding = serde_json::from_reader(BufReader::new(File::open(pll_path)?))?;
    mapped.bind_pll(&pll)?;
    let fanout =
        mapped.apply_register_enable_fanout_constraints(&[RegisterEnableFanoutConstraint::new(
            "ff_core.csr_file.*",
            4,
        )])?;
    let mapped_json = mapped.to_nextpnr_json()?;
    println!(
        "mapped cells={} sha256={:x} CE_FFs={} CE_branches={}",
        mapped.cells().len(),
        Sha256::digest(mapped_json.as_bytes()),
        fanout.rewired_registers,
        fanout.inserted_branches,
    );
    if !mapped.retiming().equivalence_signed_off {
        return Err("mapping/retiming equivalence is not signed off".into());
    }
    let imported = import_ecp5(&mapped)?;

    let architecture_started = Instant::now();
    let architecture = read_architecture_cache(BufReader::new(File::open(architecture_path)?))?;
    println!(
        "architecture loaded in {:.3?}",
        architecture_started.elapsed()
    );
    let lpf = parse_lpf(File::open(lpf_path)?)?;
    let placement = if placement_path == "-" {
        None
    } else if Path::new(&placement_path)
        .extension()
        .is_some_and(|extension| extension.eq_ignore_ascii_case("tsv"))
    {
        Some(FixedPlacement {
            bindings: read_texo_placement(&placement_path)?,
            // The Texo placement artifact was produced after native packing.
            // Re-running the deterministic native packer selects the same
            // dedicated LUT/FF pairs; importing nextpnr's pairs here would
            // change the placement problem being measured.
            lut_ff_pairs: None,
        })
    } else {
        Some(read_nextpnr_placement(&placement_path)?)
    };
    if let Some(placement) = &placement {
        println!(
            "fixed placement bindings={} LUT/FF pairs={}",
            placement.bindings.len(),
            placement.lut_ff_pairs.as_ref().map_or(0, BTreeMap::len),
        );
    } else {
        println!("placement generated by Texo");
    }

    let mut evidence = Evidence::new();
    evidence.record(Gate::SynthesisEquivalence);
    let mut stage_started = Instant::now();
    let result = implement_struo_ecp5_with_progress(
        &imported,
        &architecture,
        Ecp5FlowOptions {
            post_map_simulation: PostMapSimulationPolicy::AllowMissing,
            speed_grade: Some("8"),
            package: Some("CABGA381"),
            lpf: Some(&lpf),
            initial_placement: placement.as_ref().map(|placement| &placement.bindings),
            lut_ff_pairs: placement
                .as_ref()
                .and_then(|placement| placement.lut_ff_pairs.as_ref()),
            initial_timing_reroute: true,
            optimize_timing: placement.is_none(),
            ..Ecp5FlowOptions::default()
        },
        &mut evidence,
        |stage| report_stage(stage, &mut stage_started),
    )?;
    let setup_tns: i128 = result
        .timing
        .setup_checks
        .iter()
        .map(|check| check.slack_ps.min(0))
        .sum();
    let setup_violations = result
        .timing
        .setup_checks
        .iter()
        .filter(|check| check.slack_ps < 0)
        .count();
    println!(
        "RESULT WNS={:?} TNS={} violations={} WHS={:?} PIPs={}",
        result.timing.worst_slack_ps,
        setup_tns,
        setup_violations,
        result.timing.worst_hold_slack_ps,
        result.implementation.total_pips,
    );
    let checkpoint_started = Instant::now();
    let checkpoint = ecp5_checkpoint_ref(
        "HardwareTestTop",
        &result,
        &architecture,
        "CABGA381",
        &evidence,
    );
    println!(
        "checkpoint constructed in {:.3?}",
        checkpoint_started.elapsed()
    );
    let checkpoint_write_started = Instant::now();
    let mut writer = BufWriter::new(File::create(checkpoint_path)?);
    serde_json::to_writer(&mut writer, &checkpoint)?;
    writer.write_all(b"\n")?;
    writer.flush()?;
    println!(
        "checkpoint written in {:.3?}",
        checkpoint_write_started.elapsed()
    );
    Ok(())
}

fn report_stage(stage: Ecp5FlowStage, started: &mut Instant) {
    match stage {
        Ecp5FlowStage::Routing(RoutingProgress::Iteration { iteration, nets }) => {
            println!("route iteration={} dirty_nets={nets}", iteration + 1);
            return;
        }
        Ecp5FlowStage::TimingSnapshot {
            worst_setup_ps,
            setup_tns_ps,
            setup_violations,
            worst_hold_ps,
            ..
        } => println!(
            "timing WNS={worst_setup_ps:?} TNS={setup_tns_ps} violations={setup_violations} WHS={worst_hold_ps:?}"
        ),
        Ecp5FlowStage::Packed => println!("stage packed {:.3?}", started.elapsed()),
        Ecp5FlowStage::Placed => println!("stage fixed-placement {:.3?}", started.elapsed()),
        Ecp5FlowStage::GlobalClocksRouted => {
            println!("stage global-clocks {:.3?}", started.elapsed());
        }
        Ecp5FlowStage::Routed => println!("stage routed {:.3?}", started.elapsed()),
        Ecp5FlowStage::Timed => println!("stage timed {:.3?}", started.elapsed()),
        _ => return,
    }
    *started = Instant::now();
}

struct FixedPlacement {
    bindings: BTreeMap<String, String>,
    lut_ff_pairs: Option<BTreeMap<String, String>>,
}

fn read_texo_placement(path: &str) -> Result<BTreeMap<String, String>, Box<dyn Error>> {
    let reader = BufReader::new(File::open(path)?);
    let mut bindings = BTreeMap::new();
    let mut rows = 0usize;
    for (line_index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.is_empty() || line.starts_with('#') || line.starts_with("cell_id\t") {
            continue;
        }
        let fields = line.split('\t').collect::<Vec<_>>();
        if fields.len() != 6 {
            return Err(format!(
                "Texo placement `{path}` line {} has {} fields, expected 6",
                line_index + 1,
                fields.len()
            )
            .into());
        }
        let cell_id = fields[0].parse::<usize>().map_err(|_| {
            format!(
                "Texo placement `{path}` line {} has invalid cell ID `{}`",
                line_index + 1,
                fields[0]
            )
        })?;
        if cell_id != rows {
            return Err(format!(
                "Texo placement `{path}` line {} has cell ID {cell_id}, expected {rows}",
                line_index + 1
            )
            .into());
        }
        let cell = fields[1].to_owned();
        let bel = fields[3].to_owned();
        if bindings.insert(cell.clone(), bel).is_some() {
            return Err(format!("Texo placement maps cell `{cell}` twice").into());
        }
        rows += 1;
    }
    if rows == 0 {
        return Err(format!("Texo placement `{path}` contains no bindings").into());
    }
    Ok(bindings)
}

fn read_nextpnr_placement(path: &str) -> Result<FixedPlacement, Box<dyn Error>> {
    let document: Value = serde_json::from_reader(BufReader::new(File::open(path)?))?;
    let modules = document["modules"]
        .as_object()
        .ok_or("nextpnr placement JSON omitted its module map")?;
    if modules.len() != 1 {
        return Err(format!("nextpnr JSON has {} modules, expected one", modules.len()).into());
    }
    let cells = modules
        .values()
        .next()
        .and_then(|module| module["cells"].as_object())
        .ok_or("nextpnr placement JSON omitted its cell map")?;
    let mut comb_by_bel = BTreeMap::new();
    for (name, cell) in cells {
        if cell["type"] == "TRELLIS_COMB" {
            let bel = cell["attributes"]["NEXTPNR_BEL"]
                .as_str()
                .ok_or_else(|| format!("nextpnr cell `{name}` has no NEXTPNR_BEL"))?;
            comb_by_bel.insert(bel, name.as_str());
        }
    }
    let mut bindings = BTreeMap::new();
    let mut lut_ff_pairs = BTreeMap::new();
    for (nextpnr_name, cell) in cells {
        let cell_type = cell["type"]
            .as_str()
            .ok_or_else(|| format!("nextpnr cell `{nextpnr_name}` has no type"))?;
        if nextpnr_name.starts_with("$nextpnr_CCU2C_") || cell_type == "DCCA" {
            continue;
        }
        let nextpnr_bel = cell["attributes"]["NEXTPNR_BEL"]
            .as_str()
            .ok_or_else(|| format!("nextpnr cell `{nextpnr_name}` has no NEXTPNR_BEL"))?;
        let texo_name = nextpnr_cell_to_texo(nextpnr_name, cell_type)?;
        let texo_bel = nextpnr_bel_to_texo(nextpnr_bel)?;
        if bindings.insert(texo_name.clone(), texo_bel).is_some() {
            return Err(format!("nextpnr placement maps Texo cell `{texo_name}` twice").into());
        }
        if cell_type == "TRELLIS_FF"
            && cell["parameters"]["SD"]
                .as_str()
                .is_some_and(|value| value.trim() == "1")
        {
            let local_lut_bel = nextpnr_bel
                .strip_suffix(".FF0")
                .map(|site| format!("{site}.K0"))
                .or_else(|| {
                    nextpnr_bel
                        .strip_suffix(".FF1")
                        .map(|site| format!("{site}.K1"))
                })
                .ok_or_else(|| {
                    format!("paired nextpnr FF `{nextpnr_name}` has invalid BEL `{nextpnr_bel}`")
                })?;
            let nextpnr_lut = comb_by_bel.get(local_lut_bel.as_str()).ok_or_else(|| {
                format!("paired nextpnr FF `{nextpnr_name}` has no LUT at `{local_lut_bel}`")
            })?;
            // nextpnr inserts synthetic CCU2C boundary cells while packing a
            // carry chain. Texo derives those slices from carry metadata, so
            // neither the synthetic cell nor a pair naming it exists in the
            // imported logical design.
            if nextpnr_lut.starts_with("$nextpnr_CCU2C_") {
                continue;
            }
            let texo_lut = nextpnr_cell_to_texo(nextpnr_lut, "TRELLIS_COMB")?;
            if lut_ff_pairs
                .insert(texo_lut.clone(), texo_name.clone())
                .is_some()
            {
                return Err(format!("nextpnr pairs Texo LUT `{texo_lut}` twice").into());
            }
        }
    }
    Ok(FixedPlacement {
        bindings,
        lut_ff_pairs: Some(lut_ff_pairs),
    })
}

fn nextpnr_cell_to_texo(name: &str, cell_type: &str) -> Result<String, Box<dyn Error>> {
    if let Some(base) = name.strip_suffix("$CCU2_COMB0") {
        return Ok(format!("{base}$slice0"));
    }
    if let Some(base) = name.strip_suffix("$CCU2_COMB1") {
        return Ok(format!("{base}$slice1"));
    }
    if cell_type == "TRELLIS_IO" {
        let port = name
            .strip_suffix("$tr_io")
            .ok_or_else(|| format!("nextpnr IO cell `{name}` lacks the `$tr_io` suffix"))?;
        return Ok(if port.ends_with(']') {
            format!("${port}")
        } else {
            format!("${port}[0]")
        });
    }
    Ok(name.to_owned())
}

fn nextpnr_bel_to_texo(name: &str) -> Result<String, Box<dyn Error>> {
    let (x, rest) = name
        .strip_prefix('X')
        .and_then(|name| name.split_once("/Y"))
        .ok_or_else(|| format!("nextpnr BEL `{name}` does not begin with X#/Y#"))?;
    let (y, bel) = rest
        .split_once('/')
        .ok_or_else(|| format!("nextpnr BEL `{name}` has no site name"))?;
    let column = x
        .parse::<u32>()
        .map_err(|_| format!("nextpnr BEL `{name}` has an invalid X coordinate"))?;
    let row = y
        .parse::<u32>()
        .map_err(|_| format!("nextpnr BEL `{name}` has an invalid Y coordinate"))?;
    Ok(format!("R{row}C{column}/{bel}"))
}
